// A very small DOM for running the WindLab page scripts in Node (tests/test_js.py).
//
// It is NOT a browser: no layout (every box is 0 x 0), no CSS, no rendering, no WebGL, no real
// events beyond "call the listeners that were added". It builds the element tree of index.html
// from a JSON dump (tests/test_js.py parses the HTML with Python), gives every element the
// properties and methods app.js and its modules use (textContent, hidden, value, checked,
// dataset, classList, attributes, append / replaceChildren / after, querySelector(All) with a
// small selector engine, addEventListener / dispatchEvent / click / focus), and stubs the window
// globals the modules touch at import or start-up (matchMedia, localStorage, requestAnimationFrame,
// getComputedStyle, ResizeObserver, fetch). fetch() answers file: URLs from disk (the message
// catalog) and /api/... paths from a routes table, and logs every call.
//
// Limits: selectors cover tag, #id, .class, [attr], [attr=value], :checked, :not(...),
// descendant and child combinators and comma lists - what the page scripts use. Events do not
// capture, "input"/"change" are not generated by typing (tests set .value and dispatch), form
// submission happens only through a submit button's click() or an explicit dispatchEvent.
// Canvas 2D contexts are no-op proxies; getContext("webgl2") returns null (the preview would use
// its CPU solver). Nothing here measures or draws anything.

