const ATTR_PROPS = ["type", "name", "placeholder", "role", "href", "download", "target", "rel", "title", "step", "min",
  "max", "lang", "src", "alt", "accept", "inputmode", "pattern", "maxlength", "autocomplete", "for"];
const PROP_TO_ATTR = { htmlFor: "for", maxLength: "maxlength", colSpan: "colspan", tabIndex: "tabindex", rows: "rows" };

export class DomNode {
  constructor(doc) {
    this.ownerDocument = doc;
    this.parentNode = null;
    this.childNodes = [];
    this._listeners = new Map();
  }
  get parentElement() { return this.parentNode instanceof DomElement ? this.parentNode : null; }
  get isConnected() {
    for (let n = this; n; n = n.parentNode) if (n === this.ownerDocument) return true;
    return false;
  }
  get firstChild() { return this.childNodes[0] ?? null; }
  get lastChild() { return this.childNodes.at(-1) ?? null; }
  get children() { return this.childNodes.filter((n) => n instanceof DomElement); }
  get firstElementChild() { return this.children[0] ?? null; }
  get nextSibling() {
    if (!this.parentNode) return null;
    const s = this.parentNode.childNodes;
    return s[s.indexOf(this) + 1] ?? null;
  }
  get previousSibling() {
    if (!this.parentNode) return null;
    const s = this.parentNode.childNodes;
    return s[s.indexOf(this) - 1] ?? null;
  }
  _toNode(x) { return x instanceof DomNode ? x : new DomText(this.ownerDocument, String(x)); }
  _adopt(n) { if (n.parentNode) n.parentNode.removeChild(n); n.parentNode = this; return n; }
  appendChild(n) { this.childNodes.push(this._adopt(n)); return n; }
  append(...xs) { for (const x of xs) this.appendChild(this._toNode(x)); }
  prepend(...xs) { for (const x of xs.reverse()) this.childNodes.unshift(this._adopt(this._toNode(x))); }
  replaceChildren(...xs) { for (const c of [...this.childNodes]) this.removeChild(c); this.append(...xs); }
  insertBefore(n, ref) {
    this._adopt(n);
    const i = ref ? this.childNodes.indexOf(ref) : -1;
    if (i < 0) this.childNodes.push(n); else this.childNodes.splice(i, 0, n);
    return n;
  }
  removeChild(n) {
    const i = this.childNodes.indexOf(n);
    if (i >= 0) { this.childNodes.splice(i, 1); n.parentNode = null; }
    return n;
  }
  remove() { if (this.parentNode) this.parentNode.removeChild(this); }
  after(...xs) {
    if (!this.parentNode) return;
    let ref = this.nextSibling;
    for (const x of xs) this.parentNode.insertBefore(this._toNode(x), ref);
  }
  before(...xs) { if (this.parentNode) for (const x of xs) this.parentNode.insertBefore(this._toNode(x), this); }
  contains(n) { for (let x = n; x; x = x.parentNode) if (x === this) return true; return false; }
  get textContent() { return this.childNodes.map((c) => c.textContent).join(""); }
  set textContent(v) { this.replaceChildren(new DomText(this.ownerDocument, v == null ? "" : String(v))); }
  get innerText() { return this.textContent; }
  set innerText(v) { this.textContent = v; }
  *descendants() {
    for (const c of this.childNodes) {
      if (c instanceof DomElement) { yield c; yield* c.descendants(); }
    }
  }
  querySelectorAll(sel) {
    const list = parseList(sel);
    return [...this.descendants()].filter((el) => list.some((c) => matchesComplex(el, c)));
  }
  querySelector(sel) { return this.querySelectorAll(sel)[0] ?? null; }
  // events: own bookkeeping so the test can see what was wired, bubbling up the tree
  addEventListener(type, fn, opts) {
    if (typeof fn !== "function" && !(fn && typeof fn.handleEvent === "function")) return;
    const list = this._listeners.get(type) || [];
    list.push({ fn, once: !!(opts && opts.once) });
    this._listeners.set(type, list);
  }
  removeEventListener(type, fn) {
    const list = this._listeners.get(type) || [];
    this._listeners.set(type, list.filter((l) => l.fn !== fn));
  }
  listenerCount(type) { return (this._listeners.get(type) || []).length; }
  dispatchEvent(ev) {
    let stopped = false;
    const orig = ev.stopPropagation.bind(ev);
    ev.stopPropagation = () => { stopped = true; orig(); };
    Object.defineProperty(ev, "target", { value: this, configurable: true });
    for (let node = this; node && !stopped; node = node.parentNode) {
      Object.defineProperty(ev, "currentTarget", { value: node, configurable: true });
      for (const l of [...(node._listeners.get(ev.type) || [])]) {
        if (l.once) node.removeEventListener(ev.type, l.fn);
        if (typeof l.fn === "function") l.fn.call(node, ev); else l.fn.handleEvent(ev);
      }
      if (!ev.bubbles) break;
    }
    return !ev.defaultPrevented;
  }
}

export class DomText extends DomNode {
  constructor(doc, data) { super(doc); this.nodeType = 3; this.nodeName = "#text"; this.data = String(data); }
  get textContent() { return this.data; }
  set textContent(v) { this.data = String(v); }
  get nodeValue() { return this.data; }
}

export class DomElement extends DomNode {
  constructor(doc, tag) {
    super(doc);
    this.nodeType = 1;
    this.localName = String(tag).toLowerCase();
    this.tagName = this.nodeName = this.localName.toUpperCase();
    this._attrs = new Map();
    this.style = {};
    this._files = [];
    this._value = undefined;
    this._checked = undefined;
    this._selected = undefined;
  }
  // attributes
  getAttribute(n) { return this._attrs.has(n) ? this._attrs.get(n) : null; }
  setAttribute(n, v) { this._attrs.set(String(n), String(v)); }
  removeAttribute(n) { this._attrs.delete(n); }
  hasAttribute(n) { return this._attrs.has(n); }
  toggleAttribute(n, force) {
    const on = force === undefined ? !this._attrs.has(n) : !!force;
    if (on) this.setAttribute(n, ""); else this.removeAttribute(n);
    return on;
  }
  get attributes() { return [...this._attrs].map(([name, value]) => ({ name, value })); }
  get id() { return this.getAttribute("id") || ""; }
  set id(v) { this.setAttribute("id", v); }
  get className() { return this.getAttribute("class") || ""; }
  set className(v) { this.setAttribute("class", v); }
  get classList() {
    const self = this;
    const get = () => self.className.split(/\s+/).filter(Boolean);
    const set = (list) => { if (list.length) self.setAttribute("class", list.join(" ")); else self.removeAttribute("class"); };
    return {
      add: (...cs) => set([...new Set([...get(), ...cs])]),
      remove: (...cs) => set(get().filter((c) => !cs.includes(c))),
      contains: (c) => get().includes(c),
      toggle: (c, force) => {
        const on = force === undefined ? !get().includes(c) : !!force;
        if (on) set([...new Set([...get(), c])]); else set(get().filter((x) => x !== c));
        return on;
      },
      get length() { return get().length; },
    };
  }
  get dataset() {
    const self = this;
    const attr = (k) => "data-" + String(k).replace(/[A-Z]/g, (m) => "-" + m.toLowerCase());
    return new Proxy({}, {
      get: (_, k) => (typeof k === "string" ? (self.getAttribute(attr(k)) ?? undefined) : undefined),
      set: (_, k, v) => { self.setAttribute(attr(k), v); return true; },
      has: (_, k) => self.hasAttribute(attr(k)),
      deleteProperty: (_, k) => { self.removeAttribute(attr(k)); return true; },
      ownKeys: () => [...self._attrs.keys()].filter((k) => k.startsWith("data-"))
        .map((k) => k.slice(5).replace(/-([a-z])/g, (m, c) => c.toUpperCase())),
      getOwnPropertyDescriptor: (_, k) => ({ enumerable: true, configurable: true, value: self.getAttribute(attr(k)) }),
    });
  }
  get hidden() { return this.hasAttribute("hidden"); }
  set hidden(v) { if (v) this.setAttribute("hidden", ""); else this.removeAttribute("hidden"); }
  get disabled() { return this.hasAttribute("disabled"); }
  set disabled(v) { if (v) this.setAttribute("disabled", ""); else this.removeAttribute("disabled"); }
  get required() { return this.hasAttribute("required"); }
  set required(v) { if (v) this.setAttribute("required", ""); else this.removeAttribute("required"); }
  get checked() { return this._checked ?? this.hasAttribute("checked"); }
  set checked(v) { this._checked = !!v; }
  get selected() { return this._selected ?? this.hasAttribute("selected"); }
  set selected(v) { this._selected = !!v; }
  get options() { return this.localName === "select" ? this.children.filter((c) => c.localName === "option") : []; }
  get selectedIndex() {
    const o = this.options;
    const i = o.findIndex((x) => x.selected);
    return i >= 0 ? i : (o.length ? 0 : -1);
  }
  get value() {
    if (this.localName === "select") {
      const o = this.options;
      if (!o.length) return this._value ?? "";
      const picked = o.find((x) => x.selected) || o[0];
      return picked.value;
    }
    if (this.localName === "option") return this._value ?? this.getAttribute("value") ?? this.textContent;
    return this._value ?? this.getAttribute("value") ?? "";
  }
  set value(v) {
    v = String(v);
    if (this.localName === "select") {
      const o = this.options;
      const hit = o.find((x) => x.value === v);
      o.forEach((x) => { x.selected = x === hit; });
      if (!hit) this._value = v;
      return;
    }
    this._value = v;
  }
  get files() { return this._files; }
  set files(v) { this._files = v; }
  get type() { return this.getAttribute("type") || (this.localName === "input" ? "text" : this.localName === "button" ? "submit" : ""); }
  set type(v) { this.setAttribute("type", v); }
  get tabIndex() { return Number(this.getAttribute("tabindex") ?? -1); }
  set tabIndex(v) { this.setAttribute("tabindex", String(v)); }
  get form() { return this.closest("form"); }
  // geometry and focus: there is no layout
  getBoundingClientRect() { return { top: 0, left: 0, bottom: 0, right: 0, width: 0, height: 0, x: 0, y: 0 }; }
  get clientWidth() { return 0; }
  get clientHeight() { return 0; }
  get offsetWidth() { return 0; }
  get offsetHeight() { return 0; }
  scrollIntoView() {}
  // like a browser, an element inside an inert subtree (the page behind the modal notice) cannot take focus
  focus() {
    if (this.closest("[inert]")) return;
    this.ownerDocument.activeElement = this;
    this.dispatchEvent(new Event("focus"));
  }
  blur() { if (this.ownerDocument.activeElement === this) this.ownerDocument.activeElement = null; this.dispatchEvent(new Event("blur")); }
  setPointerCapture() {}
  releasePointerCapture() {}
  getContext(kind) {
    if (kind !== "2d") return null;  // no WebGL here
    const noop = () => undefined;
    return new Proxy({ canvas: this, measureText: () => ({ width: 0 }) }, {
      get: (t, k) => (k in t ? t[k] : noop),
      set: (t, k, v) => { t[k] = v; return true; },
    });
  }
  matches(sel) { return parseList(sel).some((c) => matchesComplex(this, c)); }
  closest(sel) {
    for (let n = this; n instanceof DomElement; n = n.parentElement) if (n.matches(sel)) return n;
    return null;
  }
  click() {
    if (this.disabled) return;
    if (this.localName === "input" && (this.type === "radio" || this.type === "checkbox")) {
      if (this.type === "radio") {
        const name = this.getAttribute("name");
        if (name) {
          const scope = this.form || this.ownerDocument;
          scope.querySelectorAll(`input[type=radio][name="${name}"]`).forEach((r) => { r.checked = r === this; });
        }
        this.checked = true;
      } else this.checked = !this.checked;
      this.dispatchEvent(new Event("click", { bubbles: true, cancelable: true }));
      this.dispatchEvent(new Event("input", { bubbles: true }));
      this.dispatchEvent(new Event("change", { bubbles: true }));
      return;
    }
    const ok = this.dispatchEvent(new Event("click", { bubbles: true, cancelable: true }));
    if (ok && this.type === "submit" && this.form) {
      this.form.dispatchEvent(new Event("submit", { bubbles: true, cancelable: true }));
    }
  }
  get outerHTML() { return `<${this.localName}${[...this._attrs].map(([k, v]) => ` ${k}="${v}"`).join("")}>`; }
}

for (const name of ATTR_PROPS) {
  if (name === "type") continue;
  Object.defineProperty(DomElement.prototype, name, {
    get() { return this.getAttribute(name) ?? ""; },
    set(v) { this.setAttribute(name, v); },
    configurable: true,
  });
}
for (const [prop, attr] of Object.entries(PROP_TO_ATTR)) {
  if (prop === "tabIndex") continue;
  Object.defineProperty(DomElement.prototype, prop, {
    get() { return this.getAttribute(attr) ?? ""; },
    set(v) { this.setAttribute(attr, v); },
    configurable: true,
  });
}

export class DomDocument extends DomNode {
  constructor() {
    super(null);
    this.ownerDocument = this;
    this.nodeType = 9;
    this.nodeName = "#document";
    this.activeElement = null;
    this.hidden = false;
    this.readyState = "complete";
    this.visibilityState = "visible";
  }
  createElement(tag) { return new DomElement(this, tag); }
  createElementNS(ns, tag) { return new DomElement(this, tag); }
  createTextNode(text) { return new DomText(this, text); }
  getElementById(id) {
    for (const el of this.descendants()) if (el.getAttribute("id") === id) return el;
    return null;
  }
  get title() { const t = this.querySelector("title"); return t ? t.textContent : ""; }
  set title(v) { const t = this.querySelector("title"); if (t) t.textContent = v; }
}

// Build the tree from the JSON the Python side writes: {"t": tag, "a": {attrs}, "c": [children | "text"]}.
export function buildDocument(tree) {
  const doc = new DomDocument();
  const make = (node, parent) => {
    if (typeof node === "string") { parent.appendChild(new DomText(doc, node)); return; }
    const el = new DomElement(doc, node.t);
    for (const [k, v] of Object.entries(node.a || {})) el.setAttribute(k, v == null ? "" : v);
    parent.appendChild(el);
    for (const c of node.c || []) make(c, el);
  };
  make(tree, doc);
  doc.documentElement = doc.children[0];
  doc.head = doc.documentElement.querySelector("head");
  doc.body = doc.documentElement.querySelector("body");
  return doc;
}

