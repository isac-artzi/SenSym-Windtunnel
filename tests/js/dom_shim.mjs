export function installDom(tree, routes, { catalog = null } = {}) {
  const document = buildDocument(tree);
  const log = [];
  const consoleLog = [];
  const g = globalThis;
  g.window = g;
  g.self = g;
  g.document = document;
  g.localStorage = new Storage();
  g.sessionStorage = new Storage();
  g.matchMedia = (q) => new MediaQuery(q);
  g.getComputedStyle = () => ({ getPropertyValue: () => "" });
  g.requestAnimationFrame = (cb) => setTimeout(() => cb(performance.now()), 0);
  g.cancelAnimationFrame = (id) => clearTimeout(id);
  g.ResizeObserver = NoopObserver;
  g.IntersectionObserver = NoopObserver;
  g.innerWidth = 1280;
  g.innerHeight = 800;
  g.devicePixelRatio = 1;
  g.scrollX = 0;
  g.scrollY = 0;
  g.scrollTo = () => {};
  g.navigator = { userAgent: "WindLab smoke test (node)", language: "en", languages: ["en"], hardwareConcurrency: 4 };
  g.location = { href: "http://localhost:8080/", origin: "http://localhost:8080", pathname: "/", search: "", hash: "",
    protocol: "http:", host: "localhost:8080" };
  if (typeof g.CustomEvent === "undefined") {
    g.CustomEvent = class CustomEvent extends Event {
      constructor(type, init = {}) { super(type, init); this.detail = init.detail ?? null; }
    };
  }
  g.HTMLElement = DomElement;
  g.Element = DomElement;
  g.Node = DomNode;
  for (const level of ["warn", "error"]) {
    const orig = console[level].bind(console);
    console[level] = (...args) => { consoleLog.push({ level, text: args.map(String).join(" ") }); orig(...args); };
  }
  // fetch: file: URLs from disk (the catalog next to i18n.js), everything else from the routes table
  g.fetch = async (input, init = {}) => {
    const url = input instanceof URL ? input.href : String(input);
    const method = (init.method || "GET").toUpperCase();
    const entry = { method, url, status: 0 };
    log.push(entry);
    if (url.startsWith("file:")) {
      let path = fileURLToPath(url);
      if (catalog && /\/i18n\/[a-z-]+\.json$/.test(path)) path = catalog;
      try {
        const body = readFileSync(path);
        entry.status = 200;
        return new Response(body, { status: 200, headers: { "content-type": path.endsWith(".json")
          ? "application/json" : "application/octet-stream" } });
      } catch (e) {
        entry.status = 404;
        return new Response(JSON.stringify({ detail: `smoke: no file ${path}` }), { status: 404,
          headers: { "content-type": "application/json" } });
      }
    }
    const path = url.split("?")[0];
    let hit = routes[`${method} ${path}`];
    if (!hit) {
      for (const [key, value] of Object.entries(routes)) {
        const [m, pattern] = key.split(" ");
        if (m !== method || !pattern.includes("*")) continue;
        const re = new RegExp("^" + pattern.split("*").map((s) => s.replace(/[.+?^${}()|[\]\\]/g, "\\$&")).join("[^/]+") + "$");
        if (re.test(path)) { hit = value; break; }
      }
    }
    if (!hit) {
      entry.status = 404;
      entry.unrouted = true;
      return new Response(JSON.stringify({ detail: `smoke: no route for ${method} ${path}` }), { status: 404,
        headers: { "content-type": "application/json" } });
    }
    entry.status = hit.status || 200;
    if (hit.binary) {
      return new Response(new Uint8Array(0), { status: entry.status, headers: { "content-type": "application/octet-stream" } });
    }
    return new Response(JSON.stringify(hit.json ?? {}), { status: entry.status,
      headers: { "content-type": "application/json" } });
  };
  return { document, log, console: consoleLog };
}
