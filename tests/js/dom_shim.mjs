// ---------------------------------------------------------------- selectors

const COMPOUND = /#([\w-]+)|\.([\w-]+)|\[([\w-]+)(?:([~|^$*]?=)(?:"([^"]*)"|'([^']*)'|([^\]]+)))?\]|:([\w-]+)(?:\(([^)]*)\))?|^([a-zA-Z][\w-]*|\*)/g;

function parseCompound(text) {
  const c = { tag: null, id: null, classes: [], attrs: [], pseudos: [] };
  let m;
  COMPOUND.lastIndex = 0;
  let consumed = 0;
  while ((m = COMPOUND.exec(text)) !== null) {
    consumed += m[0].length;
    if (m[1]) c.id = m[1];
    else if (m[2]) c.classes.push(m[2]);
    else if (m[3]) c.attrs.push({ name: m[3], op: m[4] || null, value: m[5] ?? m[6] ?? m[7] ?? null });
    else if (m[8]) c.pseudos.push({ name: m[8], arg: m[9] ?? null });
    else if (m[10]) c.tag = m[10] === "*" ? null : m[10].toLowerCase();
  }
  if (consumed !== text.length) throw new Error(`dom_shim: unsupported selector ${JSON.stringify(text)}`);
  return c;
}

function parseComplex(text) {
  // "a > b c" -> [{compound a}, ">", {compound b}, " ", {compound c}]
  const out = [];
  const parts = text.trim().split(/\s*(>)\s*|\s+/).filter((p) => p !== undefined && p !== "");
  for (const p of parts) out.push(p === ">" ? ">" : parseCompound(p));
  return out;
}

function parseList(text) {
  return String(text).split(",").map((s) => parseComplex(s)).filter((c) => c.length);
}

function matchesCompound(el, c) {
  if (c.tag && el.localName !== c.tag) return false;
  if (c.id && el.id !== c.id) return false;
  for (const cls of c.classes) if (!el.classList.contains(cls)) return false;
  for (const a of c.attrs) {
    const v = el.getAttribute(a.name);
    if (v === null) return false;
    if (a.op === "=" && v !== a.value) return false;
    if (a.op === "^=" && !v.startsWith(a.value)) return false;
    if (a.op === "$=" && !v.endsWith(a.value)) return false;
    if (a.op === "*=" && !v.includes(a.value)) return false;
    if (a.op === "~=" && !v.split(/\s+/).includes(a.value)) return false;
  }
  for (const p of c.pseudos) {
    if (p.name === "checked") { if (!el.checked) return false; }
    else if (p.name === "disabled") { if (!el.disabled) return false; }
    else if (p.name === "enabled") { if (el.disabled) return false; }
    else if (p.name === "not") { if (matchesComplex(el, parseComplex(p.arg))) return false; }
    else if (p.name === "first-child") { if (el.parentElement && el.parentElement.children[0] !== el) return false; }
    else if (p.name === "last-child") { if (el.parentElement && el.parentElement.children.at(-1) !== el) return false; }
    else throw new Error(`dom_shim: unsupported pseudo-class :${p.name}`);
  }
  return true;
}

function matchesComplex(el, complex) {
  let i = complex.length - 1;
  if (!matchesCompound(el, complex[i])) return false;
  let node = el;
  i -= 1;
  while (i >= 0) {
    const comb = complex[i] === ">" ? ">" : " ";
    if (complex[i] === ">") i -= 1;
    const want = complex[i];
    if (comb === ">") {
      node = node.parentElement;
      if (!node || !matchesCompound(node, want)) return false;
    } else {
      node = node.parentElement;
      while (node && !matchesCompound(node, want)) node = node.parentElement;
      if (!node) return false;
    }
    i -= 1;
  }
  return true;
}

